import streamlit as st

def sense(DNA):
    RNA = ''
    for nucl in DNA.upper()[:21]:
        if nucl == 'T':
            RNA += 'U'
        else:
            RNA += nucl
    return RNA

def guide_qq(RNA):
    guide_siRNA = ''
    for nucl in RNA:
        if nucl == 'C':
            guide_siRNA += 'G'
        elif nucl == 'U':
            guide_siRNA += 'A'
        elif nucl == 'A':
            guide_siRNA += 'U'
        elif nucl == 'G':
            guide_siRNA += 'C'
        else:
            st.warning('wrong sequence')
    return guide_siRNA

def passenger(DNA):
    passenger = ''
    for nucl in DNA.upper()[2:]:
        if nucl == "T":
            passenger += "U"
        else:
            passenger += nucl
    return passenger

def yi_tel(guide_siRNA, passenger):
    eff = 0
    for nucl in guide_siRNA:
        if nucl == 'A' or nucl == 'U':
            eff += 25
    AU_counter = 0
    for nucl in guide_siRNA[:7]:
        if nucl == 'A' or nucl == 'U':
            AU_counter += 1
    if (AU_counter / 7) * 100 > 50:
        eff += 25
    gc_counter = 0
    for nucl in guide_siRNA:
        if nucl == 'G' or nucl == 'C':
            gc_counter += 1
            if gc_counter > 10:
                break
        else:
            gc_counter = 0
    if gc_counter <= 10:
        eff += 25
    return eff

def rev_complement(RNA):
    rev_compl = ''
    for nucl in RNA:
        if nucl == 'A':
            rev_compl += 'U'
        elif nucl == 'G':
            rev_compl += 'C'
        elif nucl == 'C':
            rev_compl += 'G'
        elif nucl == 'U':
            rev_compl += 'A'
        else:
            rev_compl += nucl
    return rev_compl[::-1]

def Rainolds(guide_siRNA, passenger):
    efff = 0
    c_1R = 0
    for nucl in guide_siRNA:
        if nucl == 'G' or nucl == 'C':
            c_1R += 1
    if 30 < (c_1R / 21) * 100 < 52:
        efff += 100 / 7
    c_nefor = 0
    for nucl in passenger[:5]:
        if nucl == 'A' or nucl == 'U':
            c_nefor += 1
    if c_nefor >= 0.6:
        efff += 100 / 7
    if len(passenger) > 3 and passenger[::-1][2] == 'A':
        efff += 100 / 7
    if len(passenger) > 10 and passenger[::-1][9] == 'U':
        efff += 100 / 7
    if len(passenger) > 18 and (passenger[::-1][18] == 'A' or passenger[18] == 'U'):
        efff += 100 / 7
    if len(passenger) > 12 and passenger[::-1][12] != 'G':
        efff += 100 / 7

    counter = 0
    gc_counter = 0
    for nucl in guide_siRNA[18:]:
        if nucl == 'G' or nucl == 'C':
            gc_counter += 1
    if gc_counter >= 2:
        counter += 1
    if counter == 2:
        efff += 100 / 6
    return efff

def Amartsguiui(guide_siRNA):
    eff_A = 0
    if len(guide_siRNA) > 18:
        if guide_siRNA[18] == 'C' or guide_siRNA[18] == 'G':
            eff_A += 100 / 6
        if guide_siRNA[18] != 'U':
            eff_A += 100 / 6
    if len(guide_siRNA) > 0:
        if guide_siRNA[0] == 'A' or guide_siRNA[0] == 'U':
            eff_A += 100 / 6
        if guide_siRNA[0] != 'G':
            eff_A += 100 / 6
    if len(guide_siRNA) > 13:
        if guide_siRNA[13] == 'A' or guide_siRNA[13] == 'U':
            eff_A += 100 / 6

    au_counter_5 = 0
    au_counter_3 = 0
    for nucl in guide_siRNA[1:9]:
        if nucl == 'U' or nucl == 'A':
            au_counter_5 += 1
    for nucl in guide_siRNA[::-1][1:9]:
        if nucl == 'G' or nucl == 'C':
            au_counter_3 += 1
    if au_counter_3 < au_counter_5:
        eff_A += 100 / 6
    if eff_A > 100:
        eff_A = 100
    return eff_A

def sred(eff, efff, e_ff):
    return (eff + efff + e_ff) / 3

def analyze(DNA_seq):
    DNA_list = []
    eff_list = []

    for i in range(len(DNA_seq) - 23):
        DNA = DNA_seq[i:i + 23]
        RNA = sense(DNA)
        guide_siRNA = guide_qq(RNA)
        passenger_siRNA = passenger(DNA)
        eff = yi_tel(guide_siRNA, passenger_siRNA)
        efff = Rainolds(guide_siRNA, passenger_siRNA)
        e_ff = Amartsguiui(guide_siRNA)
        Eff_av = sred(eff, efff, e_ff)
        DNA_list.append(DNA)
        eff_list.append(Eff_av)

    if not eff_list:
        return None

    Eff_max = max(eff_list)
    results = []
    for i in range(len(eff_list)):
        if eff_list[i] == Eff_max:
            DNA = DNA_list[i]
            RNA = sense(DNA)
            guide_siRNA = guide_qq(RNA)
            passenger_siRNA = passenger(DNA)
            eff = yi_tel(guide_siRNA, passenger_siRNA)
            efff = Rainolds(guide_siRNA, passenger_siRNA)
            e_ff = Amartsguiui(guide_siRNA)
            Eff_av = sred(eff, efff, e_ff)
            results.append({
                "DNA, 5'-3'": DNA.upper(),
                "mRNA, 5'-3'": RNA,
                "guide_siRNA, 5'-3'": guide_siRNA,
                "passenger, 3'-5'": passenger_siRNA,
                "efficiency_1": eff,
                "efficiency_2": efff,
                "efficiency_3": e_ff,
                "Average efficiency": Eff_av,
                "Maximum efficiency": Eff_max,
            })
    return results

# ---- Streamlit-интерфейс ----
st.title("Анализ эффективности\nМалой интерферирующей РНК")
DNA_seq = st.text_input("Введите последовательность ДНК от 24 нуклеотидов(5'-3'):")

if DNA_seq:
    results = analyze(DNA_seq.strip())
    if results is None:
        st.warning("Последовательность слишком короткая (нужно минимум 24 нуклеотида).")
    else:
        for r in results:
            st.subheader("Результат")
            for key, value in r.items():
                st.write(f"**{key}:** {value}")
